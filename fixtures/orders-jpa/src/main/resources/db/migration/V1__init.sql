CREATE TABLE order_header (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no      VARCHAR(40)    NOT NULL UNIQUE,
    customer_id   VARCHAR(40)    NOT NULL,
    status        VARCHAR(20)    NOT NULL CHECK (status IN ('DRAFT', 'CONFIRMED', 'CLOSED', 'CANCELLED')),
    total_amount  NUMERIC(19, 2) NOT NULL CHECK (total_amount >= 0),
    version       BIGINT         NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE order_line (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    header_id   BIGINT         NOT NULL REFERENCES order_header (id),
    line_no     INTEGER        NOT NULL,
    sku         VARCHAR(40)    NOT NULL,
    qty         INTEGER        NOT NULL CHECK (qty > 0),
    shipped_qty INTEGER        NOT NULL CHECK (shipped_qty >= 0),
    unit_price  NUMERIC(19, 2) NOT NULL CHECK (unit_price >= 0),
    status      VARCHAR(20)    NOT NULL CHECK (status IN ('OPEN', 'CLOSED', 'CANCELLED')),
    revision    INTEGER        NOT NULL,
    version     BIGINT         NOT NULL,
    UNIQUE (header_id, line_no)
);

CREATE TABLE schedule_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id       BIGINT      NOT NULL REFERENCES order_line (id),
    seq_no        INTEGER     NOT NULL,
    qty           INTEGER     NOT NULL CHECK (qty > 0),
    delivery_date DATE        NOT NULL,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('PLANNED', 'SHIPPED', 'CANCELLED')),
    UNIQUE (line_id, seq_no)
);

CREATE TABLE change_request (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id       BIGINT         NOT NULL REFERENCES order_line (id),
    type          VARCHAR(20)    NOT NULL CHECK (type IN ('QTY', 'DATE', 'CANCEL')),
    new_qty       INTEGER,
    new_date      DATE,
    status        VARCHAR(20)    NOT NULL CHECK (status IN ('PROPOSED', 'CONFIRMED', 'COMMITTED', 'REJECTED', 'EXPIRED')),
    line_revision INTEGER        NOT NULL,
    amount_delta  NUMERIC(19, 2) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE outbox_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(60) NOT NULL,
    aggregate_id BIGINT      NOT NULL,
    payload      TEXT        NOT NULL,
    status       VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'SENT')),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at      TIMESTAMP WITH TIME ZONE
);

CREATE TABLE processed_message (
    message_id   VARCHAR(80) PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
